const invGear = character.render({ ...ctx, char: { ...c, equipment: ['0x0e7'] } });
check('сумма: экипировка не входит', invGear.includes(`Сумма: ${num(expectedSum)}`) && !invGear.includes(`Сумма: ${num(expectedSum + 1300)}`));
